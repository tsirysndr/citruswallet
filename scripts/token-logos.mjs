import { writeFile } from 'node:fs/promises';
const sources = [
  'https://tokens.uniswap.org',
  'https://raw.githubusercontent.com/megaeth-labs/mega-tokenlist/main/megaeth.tokenlist.json',
  'https://raw.githubusercontent.com/megaeth-labs/mega-tokenlist/main/megaeth.testnet.tokenlist.json',
];
const logos = {};
for (const source of sources) {
  const response = await fetch(source);
  if (!response.ok) throw new Error(`Token list unavailable: ${source}`);
  for (const token of (await response.json()).tokens) {
    if (![1, 4326, 6343].includes(token.chainId) || !/^0x[0-9a-f]{40}$/i.test(token.address)) continue;
    if (typeof token.logoURI === 'string' && token.logoURI.startsWith('https://')) logos[`${token.chainId}:${token.address.toLowerCase()}`] = token.logoURI;
  }
}
await writeFile(new URL('../app/src/token-logos.ts', import.meta.url), `// Generated by scripts/token-logos.mjs from Uniswap and MegaETH token lists.\n// Logos are display metadata, never proof of token authenticity.\nconst logos: Record<string, string> = ${JSON.stringify(logos, null, 2)};\nexport function tokenLogo(asset: { chainId: number; kind: string; contractAddress?: string | null }): string | undefined {\n  if (asset.kind === 'native') return 'https://raw.githubusercontent.com/trustwallet/assets/master/blockchains/ethereum/info/logo.png';\n  return logos[asset.chainId + ':' + asset.contractAddress?.toLowerCase()];\n}\n`);
console.log(`Updated ${Object.keys(logos).length} chain-specific token logos.`);
